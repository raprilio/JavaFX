// Generates public_html/assets/js/core/icons.js with only the Lucide icons the app actually uses.
// Any quoted string in the source that matches a Lucide icon file name is included.
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, '../public_html/assets/js');
const iconsDir = join(here, 'node_modules/lucide/dist/esm/icons');
const out = join(src, 'core/icons.js');

const files = new Set(readdirSync(iconsDir).filter((f) => f.endsWith('.mjs')).map((f) => f.slice(0, -4)));
// Alias map (e.g. trash-2 -> trash, more-vertical -> ellipsis-vertical) from lucide's iconsAndAliases.mjs
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([A-Za-z])(\d)/g, '$1-$2').toLowerCase();
const alias = new Map();
for (const m of readFileSync(join(iconsDir, '../iconsAndAliases.mjs'), 'utf8').matchAll(/export \{([^}]+)\} from '\.\/icons\/([a-z0-9-]+)\.mjs'/g)) {
  for (const part of m[1].split(',')) {
    const name = part.trim().replace(/^default as /, '');
    if (!name.endsWith('Icon') && !name.startsWith('Lucide')) alias.set(kebab(name), m[2]);
  }
}
files.forEach((f) => alias.set(f, f));
const available = new Set(alias.keys());
const walk = (d) => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : f.endsWith('.js') && f !== 'icons.js' ? [join(d, f)] : []));
const used = new Set(['circle']);
for (const file of walk(src)) {
  for (const m of readFileSync(file, 'utf8').matchAll(/['"`]([a-z0-9][a-z0-9-]{0,40})['"`]/g)) if (available.has(m[1])) used.add(m[1]);
}
// icon('name') calls whose name is not a Lucide icon are reported so typos are caught early.
const missing = new Set();
for (const file of walk(src)) {
  for (const m of readFileSync(file, 'utf8').matchAll(/icon\(\s*'([a-z0-9-]+)'/g)) if (!available.has(m[1])) missing.add(`${m[1]} (${file.split('/js/')[1]})`);
}
const attr = (o) => Object.entries(o).map(([k, v]) => `${k}="${v}"`).join(' ');
const lines = [...used].sort().map((name) => {
  const code = readFileSync(join(iconsDir, alias.get(name) + '.mjs'), 'utf8');
  const arr = code.slice(code.indexOf('= [') + 2, code.lastIndexOf('];') + 1);
  const nodes = Function(`return ${arr}`)();
  return `  '${name}': '${nodes.map(([tag, a]) => `<${tag} ${attr(a)}/>`).join('')}',`;
});
writeFileSync(out, `// Generated by build/icons.mjs from Lucide (ISC license, https://lucide.dev). Do not edit by hand.\nexport const ICONS = {\n${lines.join('\n')}\n};\n`);
console.log(`icons.js: ${used.size} icons`);
if (missing.size) { console.warn('Unknown icon names:\n  ' + [...missing].join('\n  ')); process.exitCode = 1; }
